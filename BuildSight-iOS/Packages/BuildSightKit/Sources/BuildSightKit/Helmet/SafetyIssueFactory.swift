import Foundation

public enum HelmetReviewDecision: Equatable, Sendable {
    case confirm
    /// Reviewer agrees a helmet is missing but on a different number of workers.
    case correct(confirmedCount: Int, note: String)
    case dismiss(reason: String)
}

public enum HelmetReviewError: Error, Equatable, Sendable {
    case notPermitted
    case alreadyReviewed
    case noLinkedIssue
    case reasonRequired
}

public struct HelmetReviewResult: Sendable {
    public var issue: Issue
    public var analysis: HelmetAnalysis
    public var event: IssueEvent
}

/// Turns analysis results into Safety issues and applies human review.
public enum SafetyIssueFactory {
    /// The issue id is derived from the photo id, so analysing the same photo
    /// twice (or on two devices) targets the same row and cannot duplicate it.
    public static func issueID(forPhoto photoID: UUID) -> UUID {
        DeterministicID.make(namespace: "helmet-issue", from: photoID)
    }

    public static func analysisID(forPhoto photoID: UUID) -> UUID {
        DeterministicID.make(namespace: "helmet-analysis", from: photoID)
    }

    /// Returns a new issue only when the analysis qualifies and none exists yet.
    /// `existingIssue` is looked up by the deterministic id by the caller.
    public static func makeIssue(
        for analysis: HelmetAnalysis,
        photo: EvidencePhoto,
        existingIssue: Issue?,
        now: Date
    ) -> Issue? {
        guard existingIssue == nil, case .suspectedMissingHelmet(let count)? = analysis.outcome else { return nil }
        let people = count == 1 ? "1 worker" : "\(count) workers"
        return Issue(
            id: issueID(forPhoto: photo.id),
            projectID: photo.projectID,
            areaID: photo.areaID,
            title: count == 1 ? "Possible missing helmet" : "Possible missing helmets (\(count))",
            details: "Machine-generated by the on-device helmet detector (\(analysis.modelIdentifier) \(analysis.modelVersion)): "
                + "a missing helmet was suspected on \(people). Awaiting human review. "
                + "This is a detector suggestion, not a confirmed finding.",
            category: .safety,
            priority: .high,
            reporterID: photo.creatorID,
            createdAt: now,
            evidencePhotoIDs: [photo.id],
            location: photo.location,
            origin: .helmetDetection(analysisID: analysis.id),
            review: .awaitingReview
        )
    }

    public static func review(
        decision: HelmetReviewDecision,
        issue: Issue,
        analysis: HelmetAnalysis,
        reviewerID: UUID,
        role: Role,
        now: Date
    ) -> Result<HelmetReviewResult, HelmetReviewError> {
        guard role.can(.reviewHelmetFlag) else { return .failure(.notPermitted) }
        guard issue.sourceAnalysisID == analysis.id else { return .failure(.noLinkedIssue) }
        guard issue.review == .awaitingReview else { return .failure(.alreadyReviewed) }

        var issue = issue
        var analysis = analysis
        var note: String?
        let outcome: HumanReviewStatus

        switch decision {
        case .confirm:
            outcome = .confirmed
        case .correct(let count, let text):
            // Correcting down to zero is a dismissal in all but name.
            if count <= 0 { return review(decision: .dismiss(reason: text), issue: issue, analysis: analysis, reviewerID: reviewerID, role: role, now: now) }
            outcome = .corrected
            note = "Reviewer corrected count to \(count). \(text)"
            issue.title = count == 1 ? "Missing helmet (confirmed)" : "Missing helmets (confirmed: \(count))"
        case .dismiss(let reason):
            guard !reason.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return .failure(.reasonRequired) }
            outcome = .dismissed
            note = reason
            // Dismissal closes the issue through its own audit event rather
            // than the normal verify/close path, which needs a second person.
            issue.status = .closed
        }

        issue.review = outcome
        issue.updatedAt = now
        analysis.review = outcome
        analysis.updatedAt = now
        let event = IssueEvent(projectID: issue.projectID, issueID: issue.id, actorID: reviewerID, at: now, kind: .machineReview(outcome), note: note)
        return .success(HelmetReviewResult(issue: issue, analysis: analysis, event: event))
    }
}
