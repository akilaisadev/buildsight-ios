#!/bin/zsh
# One-step signing setup for running BuildSight on your own iPhone/iPad.
# Writes Config/Signing.xcconfig (git-ignored) with your team ID and a bundle id that is
# unique to you, so Apple never reports the bundle id or app group as "not available".
#
#   ./scripts/setup_signing.sh              # detect the team from your signing certificate
#   ./scripts/setup_signing.sh ABCDE12345   # or pass your team ID (Xcode > Settings > Accounts)
#   ./scripts/setup_signing.sh --force      # overwrite an existing Config/Signing.xcconfig
set -e
cd "$(dirname "$0")/.."
OUT=Config/Signing.xcconfig
FORCE=0; TEAM=""
for arg in "$@"; do [ "$arg" = "--force" ] && FORCE=1 || TEAM="$arg"; done
if [ -f "$OUT" ] && [ "$FORCE" -eq 0 ]; then
  echo "$OUT already exists. Use --force to replace it."; cat "$OUT"; exit 0
fi
if [ -z "$TEAM" ]; then
  # Team ID = the OU of your "Apple Development" certificate (only if exactly one team is found).
  TEAMS=$(security find-identity -v -p codesigning 2>/dev/null | grep -o '"Apple Development: [^"]*"' | sort -u | while read -r name; do
    security find-certificate -c "${name//\"/}" -p 2>/dev/null | openssl x509 -noout -subject 2>/dev/null | sed -n 's/.*OU=\([A-Z0-9]\{10\}\).*/\1/p'
  done | sort -u)
  COUNT=$(echo "$TEAMS" | grep -c . || true)
  if [ "$COUNT" -eq 1 ]; then TEAM="$TEAMS"
  else echo "Could not pick a team automatically ($COUNT found). Run: ./scripts/setup_signing.sh YOURTEAMID"; echo "Find it in Xcode > Settings > Accounts, or developer.apple.com > Membership."; exit 1; fi
fi
# A bundle id only you can have: reverse-DNS + your macOS account name (letters/digits only).
ME=$(id -un | tr -cd 'a-zA-Z0-9' | tr 'A-Z' 'a-z')
cat > "$OUT" <<CFG
// Generated by scripts/setup_signing.sh. Git-ignored: this is your own signing identity.
DEVELOPMENT_TEAM = $TEAM
BUILDSIGHT_BUNDLE_ID = com.buildsight.$ME
CFG
echo "Wrote $OUT"; cat "$OUT"
echo "Next: use the BuildSight scheme, select your device, press Cmd+R."
